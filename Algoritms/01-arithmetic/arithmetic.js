//  Write the code to create functions capable of different arithmetic operations.

let add = function (num1, num2) {
    return num1 + num2;
}

let subtract = function (num1, num2) {
    return num1 - num2;
}
let multiply = function (num1, num2) {
    return num1 * num2;
}

let divide = function (num1, num2) {
    return num1 / num2;
}

console.log(add(3, 8));
console.log(subtract(3, 8));
console.log(multiply(3, 8));
console.log(divide(32, 8));
